"""In-memory WebSocket connection registry for broadcasting live alerts
and camera-status changes to every connected dashboard client.

Single-process only (no Redis/pub-sub) -- fine for the team's
single-instance mock-environment deployment; would need a shared
broker if this ever runs behind multiple backend workers.
"""

from fastapi import WebSocket


class ConnectionManager:
    def __init__(self) -> None:
        self.active_connections: list[WebSocket] = []

    async def connect(self, websocket: WebSocket) -> None:
        await websocket.accept()
        self.active_connections.append(websocket)

    def disconnect(self, websocket: WebSocket) -> None:
        if websocket in self.active_connections:
            self.active_connections.remove(websocket)

    async def broadcast(self, message: dict) -> None:
        dead: list[WebSocket] = []
        # Iterate a snapshot: clients can connect/disconnect while we await each send.
        for connection in list(self.active_connections):
            try:
                await connection.send_json(message)
            except Exception:
                dead.append(connection)
        for connection in dead:
            self.disconnect(connection)


manager = ConnectionManager()
